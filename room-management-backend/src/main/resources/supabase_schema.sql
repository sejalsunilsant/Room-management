-- ===================================================
-- Supabase (PostgreSQL) Schema Migration
-- Database: Room Management System
-- ===================================================

-- 1. Create independent tables first

-- Table: users
DROP TABLE IF EXISTS users CASCADE;
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Table: customers
DROP TABLE IF EXISTS customers CASCADE;
CREATE TABLE customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    phone_no VARCHAR(15) NOT NULL,
    email VARCHAR(50) NOT NULL,
    address TEXT
);

-- Table: rooms
DROP TABLE IF EXISTS rooms CASCADE;
CREATE TABLE rooms (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(10) NOT NULL UNIQUE,
    floor INT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'available',
    current_meter_reading INT NOT NULL,
    price NUMERIC(10, 2) NOT NULL DEFAULT 2000.00
);

-- 2. Create dependent tables

-- Table: electricity_reading
DROP TABLE IF EXISTS electricity_reading CASCADE;
CREATE TABLE electricity_reading (
    reading_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
    reading_date DATE NOT NULL,
    units_consumed INT NOT NULL,
    unit_rate NUMERIC(5, 2) NOT NULL,
    total_amount NUMERIC(10, 2) NOT NULL
);
CREATE INDEX idx_electricity_reading_room_id ON electricity_reading(room_id);

-- Table: bookings
DROP TABLE IF EXISTS bookings CASCADE;
CREATE TABLE bookings (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id) ON DELETE RESTRICT,
    room_id BIGINT NOT NULL REFERENCES rooms(room_id) ON DELETE RESTRICT,
    check_in_date DATE NOT NULL,
    check_out_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'Booked'
);
CREATE INDEX idx_bookings_customer_id ON bookings(customer_id);
CREATE INDEX idx_bookings_room_id ON bookings(room_id);

-- Table: bills
DROP TABLE IF EXISTS bills CASCADE;
CREATE TABLE bills (
    bill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT REFERENCES bookings(booking_id) ON DELETE SET NULL,
    billing_month DATE,
    rent_amount NUMERIC(10, 2),
    unit_rate NUMERIC(5, 2),
    electricity_charge NUMERIC(10, 2),
    total_amount NUMERIC(10, 2),
    paid_amount NUMERIC(10, 2) DEFAULT 0.00,
    payment_status VARCHAR(20) DEFAULT 'pending',
    previous_balance NUMERIC(10, 2) DEFAULT 0.00
);
CREATE INDEX idx_bills_booking_id ON bills(booking_id);
